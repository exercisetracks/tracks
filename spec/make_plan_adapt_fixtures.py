"""Record what the plan's fatigue step makes of a few real situations, for
the phone's port (`com.tracks.core.plan.PlanAdapt`) to match.

The step is `backend/app/calculators/plan/adapt.py`. Its inputs are a plan the
real generator built, the dashboard's CTL and ATL, and the last few days'
activities; each case below is one situation the plan has to answer:

- a 100 km ride the day before a planned run (the big unplanned session);
- a week of riding in place of the running (fatigue that is mostly
  low-impact, discounted toward a run);
- deep fatigue with no single cause (TSB under -30: moved);
- moderate fatigue (TSB under -20: shortened and made easy);
- fresh legs (nothing changes);
- a big session the day before, with the next day already taken (dropped).

Dates are fixed, never "today". Touches no database, but importing `app`
reads config:

    docker run --rm --env-file .env -v "$PWD/backend:/app" -v "$PWD/spec:/spec" \\
        tracks-backend python /spec/make_plan_adapt_fixtures.py
"""
from __future__ import annotations

import json
import sys
from datetime import date, datetime, timedelta
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, "/app")

from app.calculators.plan.adapt import adapt_to_fatigue  # noqa: E402
from app.calculators.plan.generator import plan as plan_mod  # noqa: E402

OUT = Path("/spec/fixtures/plan_adapt.json")


def _plain(v):
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    if isinstance(v, dict):
        return {k: _plain(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [_plain(x) for x in v]
    return v


def _plan(today: date, sport: str, distance: float, weeks: int, dpw: int) -> list[dict]:
    goal = SimpleNamespace(event_date=today + timedelta(weeks=weeks), event_sport=sport,
                           event_distance_meters=distance, days_per_week=dpw,
                           plan_intensity=1.0, mtb_discipline=None, cycling_discipline=None)
    history = [SimpleNamespace(sport=sport, started_at=datetime.combine(today - timedelta(days=d), datetime.min.time()),
                               distance_meters=6000.0, duration_seconds=2400, avg_heart_rate=None)
               for d in range(2, 56, 3)]
    _, workouts = plan_mod.generate_training_plan(
        goal=goal, activity_history=history, pace_bests=[], today=today, days_per_week=dpw)
    return [w for w in workouts if w["scheduled_date"] <= today + timedelta(days=13)]


def cases() -> list[dict]:
    out = []
    # Tuesday, so a moved session has the rest of a week to go to.
    tue = date(2026, 3, 3)
    run5k = _plan(tue, "running", 5000.0, 6, 4)
    ride10 = _plan(tue, "cycling", 100000.0, 8, 4)

    def case(name, workouts, today, ctl, atl, recent, imperial=False):
        got = adapt_to_fatigue(workouts, today=today, ctl=ctl, atl=atl, recent=recent, imperial=imperial)
        out.append({
            "name": name, "today": today, "ctl": ctl, "atl": atl,
            "recent": [[d, s, t] for d, s, t in recent], "imperial": imperial,
            "workouts": workouts, "expect": got,
        })

    for offset in range(0, 3):
        today = tue + timedelta(days=offset)
        case(f"hundred_km_ride_yesterday_+{offset}", run5k, today, 40.0, 52.0,
             [(today - timedelta(days=1), "cycling", 220.0)])
        case(f"a_week_of_riding_+{offset}", run5k, today, 45.0, 70.0,
             [(today - timedelta(days=k), "cycling", 90.0) for k in range(3)])
        case(f"deep_fatigue_+{offset}", run5k, today, 35.0, 70.0, [])
        case(f"moderate_fatigue_+{offset}", run5k, today, 40.0, 62.0, [])
        case(f"moderate_fatigue_imperial_+{offset}", run5k, today, 40.0, 62.0, [], imperial=True)
        case(f"fresh_+{offset}", run5k, today, 40.0, 38.0, [(today - timedelta(days=1), "running", 40.0)])
        case(f"a_big_run_before_a_ride_+{offset}", ride10, today, 50.0, 60.0,
             [(today, "running", 160.0)])
        case(f"ride_plan_deep_fatigue_+{offset}", ride10, today, 30.0, 70.0, [])
    case("no_fitness_yet", run5k, tue, 0.0, 10.0, [(tue, "cycling", 300.0)])
    return out


def main() -> None:
    data = {
        "_comment": "Generated by spec/make_plan_adapt_fixtures.py. The plan's fatigue step (adapt.py).",
        "cases": _plain(cases()),
    }
    OUT.write_text(json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n")
    print(f"wrote {len(data['cases'])} cases to {OUT}")


if __name__ == "__main__":
    main()
