"""Generate per-language data modules from the specs in this directory.

## Why this exists

Tracks now has three implementations of the same domain: Python on the server,
JavaScript in the web app, and Kotlin in the mobile core. The algorithms differ
by language, but the *tables* they operate on — which FIT sport maps to which
type, where a heart-rate zone starts, what counts as a good TSB — are the same
facts, and that is where drift actually happens. A regex reordered in one file
and not the others produces two clients that disagree about what a ride is,
with nothing failing to announce it.

So the tables live in YAML here and get generated into each language. Editing a
generated file is pointless: the next codegen run overwrites it.

## What is NOT generated

Only data. The evaluators that walk these rules are small, hand-written, and
idiomatic in each language — string-templating three of them would be far worse
to maintain than the thing it prevents. They are kept honest by golden
fixtures instead (spec/fixtures/, generated by make_fixtures.py), which every
language's test suite runs against the same expected outputs.

Usage:
    python3 spec/codegen.py           # write the generated modules
    python3 spec/codegen.py --check   # exit 1 if anything is out of date (CI)
"""

import json
import pprint
import sys
from pathlib import Path

import yaml

SPEC_DIR = Path(__file__).resolve().parent
ROOT = SPEC_DIR.parent

# Emitted into every generated file. The SPDX lines come first so the repo stays
# REUSE-compliant without the header sweep having to special-case build output
# (a stamp added there would be erased by the next codegen run).
BANNER_LINES = [
    "SPDX-FileCopyrightText: 2026 Hawk Fugagli",
    "SPDX-License-Identifier: AGPL-3.0-or-later",
    "",
    "GENERATED FILE — DO NOT EDIT.",
    "",
    "Source: spec/sport_taxonomy.yaml",
    "Regenerate: python3 spec/codegen.py",
    "",
    "Edits here are silently discarded on the next codegen run. The tables are",
    "shared across the Python backend, the JS frontend, and the Kotlin mobile",
    "core precisely so they cannot drift apart — change the spec, not this.",
]


def _banner(comment: str) -> str:
    return "\n".join(f"{comment} {line}".rstrip() for line in BANNER_LINES)


def load_spec(name: str) -> dict:
    with open(SPEC_DIR / f"{name}.yaml") as fh:
        return yaml.safe_load(fh)


# ── Sport taxonomy ───────────────────────────────────────────────────────────

def _normalise_rules(spec: dict) -> list[dict]:
    """Strip the prose fields so generated output carries only what executes.

    `why:` is documentation for whoever edits the spec. Emitting it into three
    languages would just be three copies of a comment nobody reads at the call
    site, and it would make the generated diffs noisy for wording changes.
    """
    rules = []
    for rule in spec["rules"]:
        out = {"type": rule["type"], "any": rule["any"]}
        if rule.get("none"):
            out["none"] = rule["none"]
        rules.append(out)
    return rules


def _payload(spec: dict) -> dict:
    return {
        "types": spec["types"],
        "fallback": spec["fallback"],
        "rules": _normalise_rules(spec),
    }


def gen_sport_taxonomy_python(spec: dict) -> tuple[Path, str]:
    # JSON output is valid Python here: the spec is strings and lists all the
    # way down, with no booleans, nulls, or floats to differ on.
    data = _payload(spec)
    src = (
        '"""\n' + "\n".join(BANNER_LINES) + '\n"""\n\n'
        f"SPORT_TYPES = {json.dumps(data['types'], indent=4)}\n\n"
        f"FALLBACK = {json.dumps(data['fallback'])}\n\n"
        f"RULES = {json.dumps(data['rules'], indent=4)}\n"
    )
    return ROOT / "backend/app/spec/sport_taxonomy.py", src


def gen_sport_taxonomy_js(spec: dict) -> tuple[Path, str]:
    data = _payload(spec)
    src = (
        _banner("//") + "\n\n"
        f"export const SPORT_TYPE_LIST = {json.dumps(data['types'], indent=2)};\n\n"
        f"export const FALLBACK = {json.dumps(data['fallback'])};\n\n"
        f"export const RULES = {json.dumps(data['rules'], indent=2)};\n"
    )
    return ROOT / "frontend/src/spec/sportTaxonomy.js", src


def _kotlin_conditions(entries: list) -> str:
    parts = []
    for entry in entries:
        if "all" in entry:
            inner = ", ".join(_kotlin_condition(c) for c in entry["all"])
            parts.append(f"Entry.All(listOf({inner}))")
        else:
            parts.append(f"Entry.One({_kotlin_condition(entry)})")
    return "listOf(" + ", ".join(parts) + ")"


def _kotlin_condition(cond: dict) -> str:
    field = cond["field"]
    if "equals" in cond:
        return f"Condition(Field.{field.upper()}, eq = {_kstr(cond['equals'])})"
    return f"Condition(Field.{field.upper()}, matches = {_kstr(cond['matches'])})"


def gen_sport_taxonomy_kotlin(spec: dict) -> tuple[Path, str]:
    data = _payload(spec)
    rules = []
    for rule in data["rules"]:
        none = (
            f", none = {_kotlin_conditions(rule['none'])}"
            if rule.get("none") else ""
        )
        rules.append(
            f"    Rule({_kstr(rule['type'])}, any = {_kotlin_conditions(rule['any'])}{none}),"
        )
    types = ",\n".join(f"    {_kstr(t)}" for t in data["types"])
    src = (
        _banner("//") + "\n\n"
        "package com.tracks.core.spec\n\n"
        "internal val SPORT_TYPE_LIST: List<String> = listOf(\n"
        f"{types},\n)\n\n"
        f"internal const val FALLBACK: String = {_kstr(data['fallback'])}\n\n"
        "internal val RULES: List<Rule> = listOf(\n"
        + "\n".join(rules)
        + "\n)\n"
    )
    return (
        ROOT / "mobile/core/src/commonMain/kotlin/com/tracks/core/spec/SportTaxonomyData.kt",
        src,
    )


# ── Zones ────────────────────────────────────────────────────────────────────

def _zone_payload(spec: dict) -> dict:
    """Drop the prose (`why`), keep `source` — an attribution belongs next to
    the numbers it justifies, and a reader of the generated table has no other
    way to find out where 0.85 came from."""
    def model(m: dict) -> dict:
        return {
            "basis": m["basis"],
            "source": m["source"],
            "zones": m["zones"],
        }

    return {
        "hr_models": {k: model(v) for k, v in spec["hr_models"].items()},
        "power_models": {k: model(v) for k, v in spec["power_models"].items()},
        "tsb_bands": {
            "source": spec["tsb_bands"]["source"],
            "bands": spec["tsb_bands"]["bands"],
            "unknown": spec["tsb_bands"]["unknown"],
        },
    }


def _pyliteral(value) -> str:
    """A Python literal for the generated module.

    pprint rather than json.dumps because the zone tables carry `null` for
    unbounded maxima, and JSON's spelling of that is not Python's. Patching the
    text afterwards would corrupt any string that happened to contain ": null".
    """
    return pprint.pformat(value, indent=4, width=88, sort_dicts=False)


def gen_zones_python(spec: dict) -> tuple[Path, str]:
    data = _zone_payload(spec)
    src = (
        '"""\n' + "\n".join(BANNER_LINES).replace(
            "spec/sport_taxonomy.yaml", "spec/zones.yaml") + '\n"""\n\n'
        f"HR_MODELS = {_pyliteral(data['hr_models'])}\n\n"
        f"POWER_MODELS = {_pyliteral(data['power_models'])}\n\n"
        f"TSB_BANDS = {_pyliteral(data['tsb_bands'])}\n"
    )
    return ROOT / "backend/app/spec/zones.py", src


def gen_zones_js(spec: dict) -> tuple[Path, str]:
    data = _zone_payload(spec)
    banner = _banner("//").replace("spec/sport_taxonomy.yaml", "spec/zones.yaml")
    src = (
        banner + "\n\n"
        f"export const HR_MODELS = {json.dumps(data['hr_models'], indent=2)};\n\n"
        f"export const POWER_MODELS = {json.dumps(data['power_models'], indent=2)};\n\n"
        f"export const TSB_BANDS = {json.dumps(data['tsb_bands'], indent=2)};\n"
    )
    return ROOT / "frontend/src/spec/zones.js", src


def _kstr(value: str) -> str:
    """A Kotlin string literal.

    JSON escaping covers quotes and backslashes identically, but Kotlin also
    interpolates `$`, so that has to be escaped too — otherwise a source
    attribution containing a dollar sign becomes a compile error in a generated
    file nobody is reading.
    """
    return json.dumps(value).replace("$", "\\$")


def _kotlin_zone(z: dict) -> str:
    max_pct = "null" if z["max_pct"] is None else str(z["max_pct"])
    color = f", color = {_kstr(z['color'])}" if z.get("color") else ""
    return (
        f"Zone({z['number']}, {_kstr(z['name'])}, {_kstr(z['description'])}, "
        f"{z['min_pct']}, {max_pct}{color})"
    )


def _kotlin_model(name: str, m: dict) -> str:
    zones = ",\n            ".join(_kotlin_zone(z) for z in m["zones"])
    return (
        f"    {_kstr(name)} to ZoneModel(\n"
        f"        basis = {_kstr(m['basis'])},\n"
        f"        source = {_kstr(m['source'].rstrip())},\n"
        f"        zones = listOf(\n            {zones},\n        ),\n"
        "    ),"
    )


def gen_zones_kotlin(spec: dict) -> tuple[Path, str]:
    data = _zone_payload(spec)
    banner = _banner("//").replace("spec/sport_taxonomy.yaml", "spec/zones.yaml")

    hr = "\n".join(_kotlin_model(k, v) for k, v in data["hr_models"].items())
    power = "\n".join(_kotlin_model(k, v) for k, v in data["power_models"].items())

    bands = []
    for b in data["tsb_bands"]["bands"]:
        lo = "null" if b["min"] is None else str(b["min"])
        hi = "null" if b["max"] is None else str(b["max"])
        bands.append(
            f"    TsbBand({_kstr(b['key'])}, {_kstr(b['label'])}, {lo}, {hi}, "
            f"{_kstr(b['color'])}, {_kstr(b['bg'])}, {_kstr(b['desc'])}),"
        )

    src = (
        banner + "\n\n"
        "package com.tracks.core.spec\n\n"
        f"internal val HR_MODELS: Map<String, ZoneModel> = mapOf(\n{hr}\n)\n\n"
        f"internal val POWER_MODELS: Map<String, ZoneModel> = mapOf(\n{power}\n)\n\n"
        "internal val TSB_BANDS: List<TsbBand> = listOf(\n"
        + "\n".join(bands)
        + "\n)\n\n"
        "internal const val TSB_UNKNOWN_BAND: String = "
        + _kstr(data["tsb_bands"]["unknown"]) + "\n"
    )
    return ROOT / "mobile/core/src/commonMain/kotlin/com/tracks/core/spec/ZonesData.kt", src


# ── Muscle groups ────────────────────────────────────────────────────────────

