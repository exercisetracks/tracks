# Generators that live in their own scripts because their source is backend
# data rather than a spec/ yaml, but whose output must not go stale any more
# than the rest. make_fit_profile.py is not here: it needs fitdecode, which
# only the backend image has.
DATA_SCRIPTS = ("make_coaching_data.py", "make_archetype_data.py", "make_library_data.py", "make_animation_data.py")


def _data_script_outputs():
    import importlib.util
    for name in DATA_SCRIPTS:
        spec = importlib.util.spec_from_file_location(name[:-3], ROOT / "spec" / name)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        out = mod.render()
        # One script may emit several files (the library feeds phone and server).
        yield from (out if isinstance(out, list) else [out])


def main() -> int:
    check_only = "--check" in sys.argv
    stale, written = [], []

    outputs = [(gen, name) for name, gens in GENERATORS.items() for gen in gens]
    specs = {name: load_spec(name) for name in GENERATORS}
    results = [gen(specs[name]) for gen, name in outputs] + list(_data_script_outputs())
    for path, src in results:
        existing = path.read_text() if path.exists() else None
        if existing == src:
            continue
        if check_only:
            stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(src)
        written.append(path.relative_to(ROOT))

    if check_only:
        if stale:
            print("codegen: out of date — run `python3 spec/codegen.py`:")
            for p in stale:
                print(f"  {p}")
            return 1
        print("codegen: all generated files up to date")
        return 0

    if written:
        for p in written:
            print(f"codegen: wrote {p}")
    else:
        print("codegen: nothing to do")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
