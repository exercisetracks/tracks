# ── Design tokens ────────────────────────────────────────────────────────────

def _design_banner(comment: str) -> str:
    return _banner(comment).replace("spec/sport_taxonomy.yaml", "spec/design.yaml")


def _rem(px) -> str:
    # Tailwind's own scale is in rem, so the generated one is too: a browser
    # with a larger default font scales these exactly as it scaled the originals.
    if px == 0:
        return "0px"
    if px >= 9999:
        return "9999px"
    return f"{px / 16:g}rem"


def gen_design_js(spec: dict) -> tuple[Path, str]:
    """The Tailwind theme extension. `extend`, never a replacement: the spec
    names the steps Tracks designs with, and replacing Tailwind's scale would
    delete every class (w-64, h-96) the layout uses that the spec does not name."""
    font = [spec["font"]["family"], *spec["font"]["fallback"]]
    radius = {k: _rem(v) for k, v in spec["radius"].items()}
    spacing = {k: _rem(v) for k, v in spec["spacing"].items()}
    font_size = {k: [_rem(s), {"lineHeight": _rem(lh)}] for k, (s, lh) in spec["type"].items()}
    tracking = {k: f"{v:g}em" for k, v in spec["tracking"].items()}
    weight = {k: str(v) for k, v in spec["weight"].items()}
    body = {
        "fontFamily": {"sans": font},
        "borderRadius": radius,
        "spacing": spacing,
        "fontSize": font_size,
        "letterSpacing": tracking,
        "fontWeight": weight,
    }
    lines = [
        _design_banner("//"),
        "",
        "/** Tailwind `theme.extend`, from spec/design.yaml. */",
        f"export const designTheme = {json.dumps(body, indent=2, ensure_ascii=False)};",
        "",
        "/** Component specs, for code that styles outside Tailwind (charts, canvases). */",
        f"export const designComponents = {json.dumps(spec['components'], indent=2)};",
        "",
    ]
    return ROOT / "frontend/src/design/tokens.js", "\n".join(lines)


def _kname(key: str, prefix: str) -> str:
    """A Kotlin identifier for a scale step: "2xl" → xl2, "3.5" → s3_5, DEFAULT → base."""
    if key == "DEFAULT":
        return "base"
    if key[0].isdigit() and not key.replace(".", "").isdigit():
        n, rest = key[0], key[1:]
        return f"{rest}{n}"
    return f"{prefix}{key.replace('.', '_')}" if key[0].isdigit() else key


def gen_design_kotlin(spec: dict) -> tuple[Path, str]:
    r, sp, ty = spec["radius"], spec["spacing"], spec["type"]
    wt, tr, el = spec["weight"], spec["tracking"], spec["elevation"]
    comp = spec["components"]
    k = lambda key, pre="": _kname(key, pre)

    def text_style(c: dict) -> str:
        size, lh = ty[c["type"]]
        parts = [
            "fontFamily = InterFamily",
            f"fontSize = {size}.sp",
            f"lineHeight = {lh}.sp",
            f"fontWeight = FontWeight({wt[c.get('weight', 'normal')]})",
        ]
        if "tracking" in c:
            parts.append(f"letterSpacing = ({tr[c['tracking']]:g}).em")
        if c.get("tabular"):
            parts.append('fontFeatureSettings = "tnum"')
        return "TextStyle(" + ", ".join(parts) + ")"

    out = [
        _design_banner("//"),
        "package com.tracks.app.ui.theme",
        "",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.em",
        "import androidx.compose.ui.unit.sp",
        "",
        "/** The fixed design layer, from spec/design.yaml — the same steps the web's Tailwind theme uses. */",
        "object Tokens {",
        "    object Radius {",
        *[f"        val {k(n)} = {min(v, 999)}.dp" for n, v in r.items()],
        "    }",
        "",
        "    /** Tailwind's spacing steps: `s3_5` is `p-3.5`, 14dp. */",
        "    object Space {",
        *[f"        val {k(n, 's')} = {v}.dp" for n, v in sp.items()],
        "    }",
        "",
        "    /** Font size and line height of each step of the type scale. */",
        "    object Type {",
        *[f"        val {k(n)} = TypeStep({s}.sp, {lh}.sp)" for n, (s, lh) in ty.items()],
        "    }",
        "",
        "    object Weight {",
        *[f"        val {n} = FontWeight({v})" for n, v in wt.items()],
        "    }",
        "",
        "    object Tracking {",
        *[f"        val {n} = ({v:g}).em" for n, v in tr.items()],
        "    }",
        "",
        "    object Elevation {",
        *[f"        val {n} = {v}.dp" for n, v in el.items()],
        "    }",
        "",
        "    object Card {",
        f"        val radius = Radius.{k(comp['card']['radius'])}",
        f"        val padding = Space.{k(comp['card']['padding'], 's')}",
        f"        val border = {comp['card']['border']}.dp",
        "    }",
        "",
        "    object SectionHeader {",
        f"        val style = {text_style(comp['section_header'])}",
        f"        const val uppercase = {str(comp['section_header'].get('uppercase', False)).lower()}",
        "    }",
        "",
        "    object Stat {",
        f"        val value = {text_style(comp['stat_value'])}",
        f"        val label = {text_style(comp['stat_label'])}",
        "    }",
        "",
    ]
    for name, key in (("Chip", "chip"), ("Pill", "pill"), ("Button", "button")):
        c = comp[key]
        out += [
            f"    object {name} {{",
            f"        val style = {text_style(c)}",
            f"        val radius = Radius.{k(c['radius'])}",
            f"        val paddingX = Space.{k(c['padding_x'], 's')}",
            f"        val paddingY = Space.{k(c['padding_y'], 's')}",
            *[f"        val {camel} = Space.{k(c[key2], 's')}"
              for key2, camel in (("height", "height"), ("height_sm", "heightSm"), ("padding_x_sm", "paddingXSm"))
              if key2 in c],
            *[f"        const val {camel} = {c[key2]}f"
              for key2, camel in (("tonal_alpha", "tonalAlpha"), ("neutral_alpha", "neutralAlpha"))
              if key2 in c],
            "    }",
            "",
        ]
    out[-1:] = ["}", ""]
    return ROOT / "mobile/app/src/main/java/com/tracks/app/ui/theme/TokensData.kt", "\n".join(out)


