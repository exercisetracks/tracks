# ── Sync registry ────────────────────────────────────────────────────────────

def _sync_banner(comment: str) -> str:
    # The shared banner names sport_taxonomy.yaml as its source; this file is
    # generated from sync.yaml, and someone chasing a wrong field list needs to
    # be sent to the right place.
    return _banner(comment).replace("spec/sport_taxonomy.yaml", "spec/sync.yaml")


def _kotlin_str_list(values: list) -> str:
    return "listOf(" + ", ".join(_kstr(v) for v in values) + ")"


def gen_sync_kotlin(spec: dict) -> tuple[Path, str]:
    """The entity registry the phone's merge reads.

    Only the executable facts: kind, fields, references, uid templates and
    parent links. The merge rules themselves are hand-written in
    com.tracks.core.replica.Merge and held to the server's by
    spec/fixtures/sync_scenarios.json, like every other evaluator here.
    """
    kinds = {"source": "SOURCE", "log": "LOG", "readonly": "READONLY"}
    entities = []
    for name, e in spec["entities"].items():
        refs = e.get("refs") or {}
        refs_src = "mapOf(" + ", ".join(
            f"{_kstr(k)} to {_kstr(v)}" for k, v in refs.items()
        ) + ")"
        child = e.get("children_of")
        child_src = (
            f"ChildOf(field = {_kstr(child['field'])}, entity = {_kstr(child['entity'])})"
            if child else "null"
        )
        key = _kstr(e["uid_key"]) if e.get("uid_key") else "null"
        fallback = _kstr(e["uid_key_fallback"]) if e.get("uid_key_fallback") else "null"
        entities.append(
            "    EntitySpec(\n"
            f"        name = {_kstr(name)},\n"
            f"        kind = EntityKind.{kinds[e['kind']]},\n"
            f"        fields = {_kotlin_str_list(e['fields'])},\n"
            f"        refs = {refs_src},\n"
            f"        uidKey = {key},\n"
            f"        uidKeyFallback = {fallback},\n"
            f"        childOf = {child_src},\n"
            "    ),"
        )
    src = (
        _sync_banner("//") + "\n\n"
        "package com.tracks.core.replica\n\n"
        f"internal const val SYNC_SPEC_VERSION: Int = {int(spec['version'])}\n\n"
        f"internal const val UID_NAMESPACE: String = {_kstr(spec['uid_namespace'])}\n\n"
        f"internal const val HLC_MAX_SKEW_MS: Long = {int(spec['hlc']['max_skew_ms'])}L\n\n"
        f"internal const val PULL_DEFAULT_LIMIT: Int = {int(spec['wire']['pull_default_limit'])}\n\n"
        f"internal const val PULL_MAX_LIMIT: Int = {int(spec['wire']['pull_max_limit'])}\n\n"
        "internal val ENTITY_SPECS: List<EntitySpec> = listOf(\n"
        + "\n".join(entities)
        + "\n)\n"
    )
    return (
        ROOT / "mobile/core/src/commonMain/kotlin/com/tracks/core/replica/SyncRegistryData.kt",
        src,
    )


