def _kotlin_muscle_map(m: dict) -> str:
    primary = ", ".join(_kstr(x) for x in m["primary"])
    secondary = ", ".join(_kstr(x) for x in m["secondary"])
    return f"MuscleMap(primary = listOf({primary}), secondary = listOf({secondary}))"


def gen_muscle_groups_kotlin(spec: dict) -> tuple[Path, str]:
    data = _muscle_groups_payload(spec)
    banner = _banner("//").replace("spec/sport_taxonomy.yaml", "spec/muscle_groups.yaml")

    cat_muscles = ",\n".join(
        f"    {_kstr(k)} to {_kotlin_muscle_map(v)}"
        for k, v in data["category_muscles"].items()
    )
    muscle_labels = ",\n".join(
        f"    {_kstr(k)} to {_kstr(v)}" for k, v in data["muscle_labels"].items()
    )
    category_labels = ",\n".join(
        f"    {_kstr(k)} to {_kstr(v)}" for k, v in data["category_labels"].items()
    )

    regions = ",\n".join(
        f"    {_kstr(k)} to BodyRegion("
        f"muscle = {_kstr(v['muscle'])}, "
        f"slug = {_kstr(v['slug'])}, "
        f"view = {_kstr(v['view'])})"
        for k, v in data["body_viewer_regions"].items()
    )

    src = (
        banner + "\n\n"
        "package com.tracks.core.spec\n\n"
        f"internal val CATEGORY_MUSCLES: Map<String, MuscleMap> = mapOf(\n{cat_muscles},\n)\n\n"
        f"internal val MUSCLE_LABELS: Map<String, String> = mapOf(\n{muscle_labels},\n)\n\n"
        f"internal val CATEGORY_LABELS: Map<String, String> = mapOf(\n{category_labels},\n)\n\n"
        f"public val BODY_VIEWER_REGIONS: Map<String, BodyRegion> = mapOf(\n{regions},\n)\n"
    )
    return (
        ROOT / "mobile/core/src/commonMain/kotlin/com/tracks/core/spec/MuscleGroupsData.kt",
        src,
    )


# ── Strength: equipment + experience levels ─────────────────────────────────

def _strength_payload(spec: dict) -> dict:
    return {
        "equipment": spec["equipment"],
        "experience_default_fallback_tier": spec["experience_default_fallback_tier"],
        "experience_levels": spec["experience_levels"],
    }


def _experience_table(levels: list[dict]) -> dict:
    return {
        lvl["value"]: {
            "label": lvl["label"],
            "blurb": lvl["blurb"],
            "default_tier": lvl["default_tier"],
            "max_difficulty": lvl["max_difficulty"],
            "stage_floor": lvl["stage_floor"],
            "starting_weight_factor": lvl["starting_weight_factor"],
        }
        for lvl in levels
    }


def gen_strength_python(spec: dict) -> tuple[Path, str]:
    data = _strength_payload(spec)
    equipment = data["equipment"]
    levels = data["experience_levels"]
    banner = "\n".join(BANNER_LINES).replace(
        "spec/sport_taxonomy.yaml", "spec/strength.yaml")

    valid_equipment = "{" + ", ".join(json.dumps(e["value"]) for e in equipment) + "}"
    experience_levels = "(" + ", ".join(json.dumps(l["value"]) for l in levels) + ")"

    src = (
        '"""\n' + banner + '\n"""\n\n'
        f"EQUIPMENT = {json.dumps(equipment, indent=4)}\n\n"
        f"VALID_EQUIPMENT = {valid_equipment}\n\n"
        f"EXPERIENCE_LEVELS = {experience_levels}\n\n"
        f"EXPERIENCE_TABLE = {_pyliteral(_experience_table(levels))}\n\n"
        f"UNKNOWN_FALLBACK_TIER = {data['experience_default_fallback_tier']}\n"
    )
    return ROOT / "backend/app/spec/strength.py", src


def gen_strength_js(spec: dict) -> tuple[Path, str]:
    data = _strength_payload(spec)
    equipment = data["equipment"]
    levels = data["experience_levels"]
    banner = _banner("//").replace("spec/sport_taxonomy.yaml", "spec/strength.yaml")

    src = (
        banner + "\n\n"
        f"export const EQUIPMENT = {json.dumps(equipment, indent=2)};\n\n"
        f"export const VALID_EQUIPMENT = {json.dumps([e['value'] for e in equipment])};\n\n"
        f"export const EXPERIENCE_LEVELS = {json.dumps([l['value'] for l in levels])};\n\n"
        f"export const EXPERIENCE_TABLE = {json.dumps(_experience_table(levels), indent=2)};\n\n"
        f"export const UNKNOWN_FALLBACK_TIER = {data['experience_default_fallback_tier']};\n"
    )
    return ROOT / "frontend/src/spec/strength.js", src


def _kotlin_equipment_option(e: dict) -> str:
    return f"EquipmentOption({_kstr(e['value'])}, {_kstr(e['label'])}, {_kstr(e['description'])})"


def _kotlin_experience_entry(lvl: dict) -> str:
    max_diff = "null" if lvl["max_difficulty"] is None else str(lvl["max_difficulty"])
    return (
        "ExperienceEntry(\n"
        f"        label = {_kstr(lvl['label'])},\n"
        f"        blurb = {_kstr(lvl['blurb'])},\n"
        f"        defaultTierEndurance = {lvl['default_tier']['endurance']},\n"
        f"        defaultTierStrength = {lvl['default_tier']['strength']},\n"
        f"        maxDifficulty = {max_diff},\n"
        f"        stageFloor = {lvl['stage_floor']},\n"
        f"        startingWeightFactor = {lvl['starting_weight_factor']},\n"
        "    )"
    )


def gen_strength_kotlin(spec: dict) -> tuple[Path, str]:
    data = _strength_payload(spec)
    equipment = data["equipment"]
    levels = data["experience_levels"]
    banner = _banner("//").replace("spec/sport_taxonomy.yaml", "spec/strength.yaml")

    equipment_list = ",\n".join(f"    {_kotlin_equipment_option(e)}" for e in equipment)
    valid_equipment = ", ".join(_kstr(e["value"]) for e in equipment)
    experience_levels = ", ".join(_kstr(l["value"]) for l in levels)
    table = "\n".join(
        f"    {_kstr(l['value'])} to {_kotlin_experience_entry(l)}," for l in levels
    )

    src = (
        banner + "\n\n"
        "package com.tracks.core.spec\n\n"
        f"internal val EQUIPMENT: List<EquipmentOption> = listOf(\n{equipment_list},\n)\n\n"
        f"internal val VALID_EQUIPMENT: Set<String> = setOf({valid_equipment})\n\n"
        f"internal val EXPERIENCE_LEVELS: List<String> = listOf({experience_levels})\n\n"
        f"internal val EXPERIENCE_TABLE: Map<String, ExperienceEntry> = mapOf(\n{table}\n)\n\n"
        f"internal const val UNKNOWN_FALLBACK_TIER: Int = {data['experience_default_fallback_tier']}\n"
    )
    return (
        ROOT / "mobile/core/src/commonMain/kotlin/com/tracks/core/spec/StrengthData.kt",
        src,
    )


