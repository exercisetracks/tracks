/**
 * [vdotToPaces] against the backend's `vdot_to_paces`, at every half-point of
 * VDOT from 25 to 85.
 *
 * The exhaustive sweep is there for one reason: the reference rounds to one
 * decimal in Python, and this rounds in Kotlin. The two languages break ties
 * differently, and a single tenth of a second matters here — the pace is
 * divided into a million and truncated to reach the speed target a step
 * carries, so a tie broken the other way moves the number the watch is given.
 * Spot-checking three values would not have found that; sweeping the range
 * either finds it or proves it does not happen.
 */
class VdotPacesTest {

    private val zones = listOf("recovery", "easy", "marathon", "threshold", "interval", "repetition")

    @Test
    fun `paces match the backend across the whole VDOT range`() {
        var checked = 0
        for (row in REFERENCE.split(';')) {
            val (vdot, values) = row.split(':')
            val expected = values.split(',').map { it.toDouble() }
            val actual = vdotToPaces(vdot.toDouble())
            for ((index, zone) in zones.withIndex()) {
                assertEquals(
                    expected[index], actual.getValue(zone),
                    "VDOT $vdot, $zone",
                )
            }
            checked++
        }
        assertEquals(121, checked, "the reference table lost rows")
    }

